"""Edit model v1 (Pydantic). JSON field names are camelCase so the same JSON round-trips through
schema/EditModel.kt (kotlinx.serialization) and schema/edit_model.json (generated by scripts/gen_schema.py).

All positions are integer samples at Project.sampleRate. Ranges are half-open: [startSample, endSample).
"""
from __future__ import annotations

from typing import Any, Literal, Optional

from pydantic import BaseModel, ConfigDict, Field, model_validator

SCHEMA_VERSION = 1


class _M(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")


class Range(_M):
    """A window into a source clip. White marker = startSample, orange marker = endSample (exclusive)."""
    startSample: int = Field(ge=0)
    endSample: int = Field(ge=0)

    @model_validator(mode="after")
    def _ordered(self):
        if self.endSample <= self.startSample:
            raise ValueError("endSample must be > startSample")
        return self

    @property
    def length(self) -> int:
        return self.endSample - self.startSample


class Snap(_M):
    type: Literal["seconds", "beats"] = "seconds"
    value: float = Field(default=0.1, gt=0, description="Grid size: seconds (type=seconds) or beats (type=beats).")
    bpm: Optional[float] = Field(default=None, gt=0, le=400, description="Required when type=beats.")

    @model_validator(mode="after")
    def _bpm(self):
        if self.type == "beats" and self.bpm is None:
            raise ValueError("snap.bpm is required when snap.type == 'beats'")
        return self

    def unit_samples(self, sr: int) -> float:
        """Length of one snap unit in (fractional) samples."""
        if self.type == "beats":
            return self.value * 60.0 / float(self.bpm) * sr
        return self.value * sr


class SourceClip(_M):
    """An immutable audio buffer uploaded with the render request (multipart part name == id)."""
    id: str = Field(min_length=1, max_length=64, pattern=r"^[A-Za-z0-9_.\-]+$")
    name: Optional[str] = None
    numSamples: Optional[int] = Field(default=None, ge=1, description="Informational; the decoded file is authoritative.")
    channels: Optional[int] = Field(default=None, ge=1, le=2)


class Crossfade(_M):
    """Centred on each item boundary. equal_power: gain_out = cos(w*pi/2), gain_in = sin(w*pi/2) (constant power for
    uncorrelated audio). linear: gain_out = 1-w, gain_in = w (constant amplitude, best for identical/correlated audio)."""
    lengthMs: float = Field(default=75.0, ge=50.0, le=100.0)
    curve: Literal["equal_power", "linear"] = "equal_power"


class LaneItem(_M):
    id: str = Field(min_length=1, max_length=64)
    sourceClipId: str
    range: Range
    laneStartSample: int = Field(ge=0, description="Timeline position of range.startSample.")
    mode: Literal["add", "replace"] = "add"
    gainDb: float = Field(default=0.0, ge=-60.0, le=12.0, description="Per-item (clip) gain, pre-bus.")
    fadeInMs: float = Field(default=0.0, ge=0.0, le=60000.0)
    fadeOutMs: float = Field(default=0.0, ge=0.0, le=60000.0)
    crossfade: Crossfade = Crossfade()

    @property
    def laneEndSample(self) -> int:
        return self.laneStartSample + self.range.length


class Processor(_M):
    id: str = Field(min_length=1, max_length=64)
    type: str = Field(min_length=1, max_length=32, description="Registry key, e.g. 'delay', 'eq'.")
    enabled: bool = True
    params: dict[str, Any] = Field(default_factory=dict)
    fadeInMs: float = Field(default=0.0, ge=0.0, le=60000.0)
    fadeOutMs: float = Field(default=0.0, ge=0.0, le=60000.0)


class Lane(_M):
    id: str = Field(min_length=1, max_length=64)
    name: str = ""
    order: int = 0
    colorArgb: Optional[int] = Field(default=None, ge=0, le=0xFFFFFFFF)
    gainDb: float = Field(default=0.0, ge=-60.0, le=12.0,
                          description="Lane BUS gain: applied once to the lane sum (after items, crossfades and the "
                                      "processor chain), never per item.")
    pan: float = Field(default=0.0, ge=-1.0, le=1.0,
                       description="Lane bus pan, constant power: L=cos((pan+1)pi/4)*sqrt2, R=sin((pan+1)pi/4)*sqrt2 "
                                   "(unity at centre).")
    mute: bool = Field(default=False, description="Mute wins over solo.")
    solo: bool = Field(default=False, description="If any lane is soloed only soloed, unmuted lanes play. "
                                                  "The main clip is not affected by solo.")
    items: tuple[LaneItem, ...] = ()
    processorChain: tuple[Processor, ...] = ()


class Selection(_M):
    """UI-only state. Ignored by the renderer."""
    sourceClipId: str
    range: Range


class Project(_M):
    version: Literal[1] = SCHEMA_VERSION
    id: str = Field(min_length=1, max_length=64)
    sampleRate: int = Field(default=44100, ge=8000, le=192000)
    snap: Snap = Snap()
    clips: tuple[SourceClip, ...] = ()
    mainClipId: Optional[str] = Field(default=None, description="Source clip played from timeline sample 0 (the 'main' view).")
    mainGainDb: float = Field(default=0.0, ge=-60.0, le=12.0)
    mainMute: bool = False
    lanes: tuple[Lane, ...] = ()
    selection: Optional[Selection] = None
    masterLimiter: Literal["soft_clip", "gain_compensation"] = Field(
        default="soft_clip",
        description="soft_clip: static soft knee above the threshold (block-local). gain_compensation: one global gain "
                    "so the loudest master sample lands at the threshold (needs a pre-scan), then soft_clip as a safety.")
    softClipThresholdDb: float = Field(default=-1.0, ge=-12.0, le=-0.5,
                                       description="Master is bit-transparent below this level; above it a tanh knee approaches the -0.1 dBFS "
                                                   "ceiling, so the output never reaches 0 dBFS.")

    @model_validator(mode="after")
    def _refs(self):
        ids = [c.id for c in self.clips]
        if len(set(ids)) != len(ids):
            raise ValueError("duplicate clip ids")
        known = set(ids)
        if self.mainClipId is not None and self.mainClipId not in known:
            raise ValueError(f"mainClipId '{self.mainClipId}' is not in clips")
        seen: set[str] = set()
        for lane in self.lanes:
            for obj in (lane, *lane.items, *lane.processorChain):
                if obj.id in seen:
                    raise ValueError(f"duplicate id '{obj.id}'")
                seen.add(obj.id)
            for it in lane.items:
                if it.sourceClipId not in known:
                    raise ValueError(f"item '{it.id}' references unknown clip '{it.sourceClipId}'")
        return self

    # convenience lookups
    def lane(self, lane_id: str) -> Lane:
        return next(l for l in self.lanes if l.id == lane_id)

    def ordered_lanes(self) -> list[Lane]:
        return sorted(self.lanes, key=lambda l: (l.order, l.id))


class EditOp(_M):
    """One undoable edit. before/after hold the JSON of each target (null = did not exist / was deleted)."""
    opId: str
    type: str = Field(description="e.g. addItem, moveItem, deleteItem, setLane, addProcessor, setProcessor, setSnap ...")
    targetIds: tuple[str, ...]
    before: dict[str, Optional[dict[str, Any]]] = Field(default_factory=dict)
    after: dict[str, Optional[dict[str, Any]]] = Field(default_factory=dict)


class EditHistory(_M):
    """Immutable undo state: snapshots[i] is the project after ops[i-1]; cursor indexes the current snapshot."""
    snapshots: tuple[Project, ...]
    ops: tuple[EditOp, ...] = ()
    cursor: int = 0

    @model_validator(mode="after")
    def _shape(self):
        if len(self.snapshots) != len(self.ops) + 1:
            raise ValueError("snapshots must have exactly one more entry than ops")
        if not 0 <= self.cursor < len(self.snapshots):
            raise ValueError("cursor out of range")
        return self
