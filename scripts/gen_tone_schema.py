"""Writes schema/tone_schema.json (same body as GET /tone/schema) and the bundled Kotlin ranges
schema/kotlin-presets/ToneRanges.kt. --check fails if either is stale."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from app.tone.profile import SCHEMA_VERSION, SPEC, schema_doc  # noqa: E402


def kotlin() -> str:
    lines = ["// GENERATED by scripts/gen_tone_schema.py from app/tone/profile.py SPEC. Do not edit.",
             "package com.david.aimusicengineer.presets", "",
             "/** Offline copy of GET /tone/schema ranges. min/max = freestyle clamp; presetMin/presetMax = preset. */",
             "data class NumRange(val min: Double, val max: Double, val default: Double, val unit: String,",
             "                    val presetMin: Double, val presetMax: Double) {",
             "    fun clamp(v: Double): Double = if (!v.isFinite()) default else v.coerceIn(min, max)  // same as the server",
             "}", "", "object ToneRanges {", f"    const val SCHEMA_VERSION = {SCHEMA_VERSION}",
             f"    const val MAX_BANDS = {SPEC['eq']['bands']['maxItems']}",
             "    val numbers: Map<String, NumRange> = mapOf("]
    rows = []
    for sec, fields in SPEC.items():
        items = fields["bands"]["item"].items() if sec == "eq" else fields.items()
        for k, sp in items:
            if sp["kind"] == "number":
                key = f"eq.bands.{k}" if sec == "eq" else f"{sec}.{k}"
                rows.append(f'        "{key}" to NumRange({float(sp["min"])}, {float(sp["max"])}, '
                            f'{float(sp["default"])}, "{sp["unit"]}", {float(sp["presetMin"])}, {float(sp["presetMax"])}),')
    rows[-1] = rows[-1].rstrip(",")
    lines += rows + ["    )", "    val enums: Map<String, List<String>> = mapOf("]
    er = []
    for sec, fields in SPEC.items():
        items = fields["bands"]["item"].items() if sec == "eq" else fields.items()
        for k, sp in items:
            if sp["kind"] == "enum":
                key = f"eq.bands.{k}" if sec == "eq" else f"{sec}.{k}"
                er.append(f'        "{key}" to listOf(' + ", ".join(f'"{o}"' for o in sp["options"]) + "),")
    er[-1] = er[-1].rstrip(",")
    lines += er + ["    )", "    fun clamp(key: String, v: Double): Double = numbers.getValue(key).clamp(v)", "}", ""]
    return "\n".join(lines)


OUT = {ROOT / "schema/tone_schema.json": json.dumps(schema_doc(), indent=2) + "\n",
       ROOT / "schema/kotlin-presets/ToneRanges.kt": kotlin()}
if __name__ == "__main__":
    stale = [p for p, t in OUT.items() if not p.exists() or p.read_text() != t]
    if "--check" in sys.argv:
        print("stale: " + ", ".join(map(str, stale)) if stale else "ok")
        sys.exit(1 if stale else 0)
    for p, t in OUT.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(t)
    print("wrote", *OUT)
